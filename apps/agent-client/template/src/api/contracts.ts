/**
 * Shared wire-level contracts.
 *
 * Success responses return the resource (or a page envelope) directly.
 * Errors always use `{ error: { code, message, details? } }`.
 */

export type ApiErrorCode =
  | 'bad_request'
  | 'unauthorized'
  | 'forbidden'
  | 'not_found'
  | 'conflict'
  | 'internal_error'

export interface ApiErrorBody {
  error: {
    code: ApiErrorCode
    message: string
    details?: unknown
  }
}

export interface PageDto<T> {
  items: T[]
  total: number
  page: number
  page_size: number
}

export interface PageQuery {
  page?: number
  page_size?: number
  keyword?: string
}

export interface RequestMeta {
  request_id: string
  trace_id: string
  /** ISO-8601 timestamp generated by the server. */
  server_time: string
  /** True when an HTTP transport served a cached GET response while offline. */
  from_cache?: boolean
}

export interface ApiResponse<T> {
  data: T
  status: number
  meta: RequestMeta
  headers: Record<string, string>
}

export type ApiMethod = 'GET' | 'POST' | 'PATCH' | 'PUT' | 'DELETE'

export interface ApiRequest {
  method: ApiMethod
  path: string
  query?: Record<string, unknown>
  body?: unknown
  headers?: Record<string, string>
}

export interface ApiTransport {
  request<T>(request: ApiRequest): Promise<ApiResponse<T>>
}
